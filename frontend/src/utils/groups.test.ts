import assert from 'node:assert/strict';
import type { Node } from '@xyflow/react';
import type { NodeData } from '../types';
import { createGroup, groupContents, selectionWithContents, groupDragSnapshot, expandGroupDrag, isGroup, fitGroup } from './groups.ts';
import { cloneGraphIds, convertSelection, flattenGraph, unpackSubgraph } from './subgraphs.ts';
import { serializeFlowForStorage, parseStoredFlow, hydrateFlowWithLatestSpecs } from './workflowPersistence.ts';
import { compileWorkflow } from './compileWorkflow.ts';

const spec = { type: 'Test', display_name: 'Test', category: 'test', input: { required: {} }, output: [] };
const node = (id: string, x: number, y: number): Node<NodeData> => ({ id, type: 'dynamic', position: { x, y }, measured: { width: 300, height: 200 }, data: { opType: 'Test', nodeSpec: spec, values: {} } });
const original = [node('a', 100, 100), node('b', 500, 150)];
const grouped = createGroup(original.map(n => ({ ...n, selected: true })));
const group = grouped.find(isGroup)!;
assert.deepEqual(groupContents(group, grouped).map(n => n.id), ['a', 'b']);
assert.deepEqual(selectionWithContents(grouped).map(n => n.id), grouped.map(n => n.id), 'copying a selected frame includes its contents');
const snapshot = groupDragSnapshot(grouped, group.id, false);
const changes = expandGroupDrag([{ id: group.id, type: 'position', position: { x: group.position.x + 20, y: group.position.y + 50 }, dragging: true }], snapshot);
assert.deepEqual(changes.find(c => 'id' in c && c.id === 'a'), { id: 'a', type: 'position', position: { x: 120, y: 150 }, dragging: true });
assert.equal(expandGroupDrag([changes[0]], groupDragSnapshot(grouped, group.id, true)).length, 1, 'Alt drag only moves the frame');
const both = grouped.map(n => ({ ...n, selected: true }));
const combined = expandGroupDrag(changes, groupDragSnapshot(both, group.id, false));
assert.equal(combined.length, 3, 'selected members are not moved twice');
const nested = createGroup(grouped);
const outer = nested.at(-1)!;
assert.deepEqual(new Set(groupContents(outer, nested).map(n => n.id)), new Set(grouped.map(n => n.id)), 'nested groups are spatially contained');
const nestedDrag = expandGroupDrag([{ id: outer.id, type: 'position', position: { x: 1000, y: 1000 } }], groupDragSnapshot(nested, outer.id, false));
assert.equal(new Set(nestedDrag.map(c => 'id' in c && c.id)).size, nestedDrag.length);
const overlap = { ...group, id: 'overlap', position: { x: group.position.x + 100, y: group.position.y } };
assert(!groupContents(group, [...grouped, overlap]).some(n => n.id === 'overlap'), 'partially overlapping groups are independent');
const movingOut = grouped.map(n => n.id === 'a' ? { ...n, position: { x: 9999, y: 9999 } } : n);
assert(!groupContents(group, movingOut).some(n => n.id === 'a'), 'moving a node outside changes membership without a stored parent');
assert(fitGroup(group, movingOut).data.group!.width < group.data.group!.width);
const graph = { nodes: nested, edges: [] };
assert.deepEqual(compileWorkflow(graph), compileWorkflow({ nodes: original, edges: [] }), 'groups never create tasks');
const restored = hydrateFlowWithLatestSpecs(parseStoredFlow(JSON.parse(JSON.stringify(serializeFlowForStorage(nested, []))))!, { Test: spec });
assert.equal(restored.invalidNodeTypes.length, 0);
assert.deepEqual(restored.nodes.filter(isGroup).map(n => [n.position, n.data.group, n.data.color]), nested.filter(isGroup).map(n => [n.position, n.data.group, n.data.color]));
const wrapped = convertSelection(graph, 'Grouped subgraph');
const wrapper = wrapped.nodes.find(n => n.data.subgraph)!;
assert.equal(wrapper.data.subgraph!.nodes.filter(isGroup).length, 2, 'group layout survives conversion to a subgraph');
assert.deepEqual(compileWorkflow(wrapped), compileWorkflow(graph));
assert.equal(unpackSubgraph(wrapped, wrapper.id).nodes.filter(isGroup).length, 2);
const blueprint = cloneGraphIds(wrapped);
assert.equal(blueprint.nodes[0].data.subgraph!.nodes.filter(isGroup).length, 2, 'blueprint copies include group frames');
assert(!flattenGraph(blueprint).nodes.some(n => original.some(o => o.id === n.id)), 'blueprint instances have independent node IDs');
assert.deepEqual(compileWorkflow({ nodes: nested.filter(n => n.id !== outer.id), edges: [] }), compileWorkflow(graph), 'deleting only a group leaves processing nodes intact');
assert.throws(() => parseStoredFlow({ nodes: [{ id: 'bad', data: { group: { width: -1, height: 200 } } }], edges: [] }), /group dimensions/);
console.log('group membership, movement, nesting, persistence, subgraph/blueprint and execution tests passed');
